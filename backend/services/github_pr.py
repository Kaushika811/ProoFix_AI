import hashlib
import re
import base64
from contextlib import contextmanager
from pathlib import Path
from urllib.parse import urlparse

from backend.config import Settings, get_settings
from backend.models.pr import PublicationResult
from backend.models.proof import VerificationBundle
from backend.services.proof_bundle import (
    compute_bundle_hash,
    generate_verification_workflow,
    proof_artifact_hash,
    proof_bundle_relative_path,
    serialize_verification_bundle,
    workflow_relative_path,
)


class GitHubPRService:
    def __init__(self, settings: Settings | None = None):
        self.settings = settings or get_settings()

    def format_pr_body_with_proof(
        self,
        bundle: VerificationBundle,
        why_section: str,
        what_section: str,
        review_section: str = "",
        *,
        published_head_sha: str | None = None,
        artifact_hash: str | None = None,
    ) -> str:
        before = next(s for s in bundle.steps if s.name == "reproduction_before")
        after = next(s for s in bundle.steps if s.name == "reproduction_after")
        mutation = next((s for s in bundle.steps if s.name == "mutation_test"), None)
        security = next((s for s in bundle.steps if s.name == "security_delta"), None)

        if bundle.reproduction_confidence == "exact_test":
            reproduction_label = "Exact failing test pinned"
            reproduction_detail = "Same test is replayed before and after the patch"
            before_label = "Base commit — exact failing test"
            after_label = "Tested patch — same test"
        else:
            reproduction_label = "Full test suite only"
            reproduction_detail = "Lower-confidence: no single failing test was identified"
            before_label = "Base commit — full suite"
            after_label = "Tested patch — full suite"

        mutation_status = (
            f"Replay included — {mutation.expected_result}"
            if mutation and mutation.command
            else "Not available — remains unmeasured"
        )
        security_status = (
            f"Replay included — {security.expected_result}"
            if security and security.command
            else "Not available — remains unmeasured"
        )
        quoted_review = "\n> ".join(review_section.strip().splitlines())
        review_alert = (
            f"> [!WARNING]\n> **Human review required:** {quoted_review}\n"
            if review_section
            else "> [!NOTE]\n> **Human decision required:** inspect the evidence and current Checks status before merging.\n"
        )

        body = (
            "# ProoFix evidence summary\n\n"
            f"{review_alert}\n"
            "The **Checks** tab is authoritative for the current PR head. Verification runs on "
            "GitHub's runners with **zero LLM calls**.\n\n"
            "## Evidence at a glance\n\n"
            "| Review question | Evidence |\n"
            "| --- | --- |\n"
            f"| Was the reported failure reproduced? | **{reproduction_label}** |\n"
            f"| Is the same behavior checked after the patch? | {reproduction_detail} |\n"
            f"| Is test strength challenged? | {mutation_status} |\n"
            f"| Is the security delta checked? | {security_status} |\n"
            "| Does verification call an LLM? | **No** — deterministic command replay |\n\n"
            "## Evidence path\n\n"
            "**Base failure** → **diagnosis** → **tested patch** → **same test replay** → "
            "**mutation/security checks** → **human decision**\n\n"
            f"## Why\n{why_section}\n\n"
            f"## What changed\n{what_section}\n\n"
            "## Reproduce the evidence\n\n"
            "| State | Pinned commit | Expected result |\n"
            "| --- | --- | --- |\n"
            f"| {before_label} | `{before.base_commit[:12] or 'unavailable'}` | {before.expected_result} |\n"
            f"| {after_label} | `{after.patch_commit[:12] or 'unavailable'}` | {after.expected_result} |\n\n"
            f"**Before**\n```bash\n{before.command}\n```\n\n"
            f"**After**\n```bash\n{after.command}\n```\n"
        )
        body += (
            "\n---\n\n"
            "<details>\n"
            "<summary><strong>Proof identity and integrity hashes</strong></summary>\n\n"
            f"- Proof bundle hash: `{bundle.bundle_hash}`\n"
            f"- Tested patch SHA: `{after.patch_commit or 'unavailable'}`\n"
            f"- Proof artifact SHA-256: `{artifact_hash or 'unavailable'}`\n"
            f"- Published head SHA: `{published_head_sha or 'unavailable'}`\n\n"
            "</details>\n\n"
            "<sub>Generated by ProoFix. Axis scores are secondary review aids; executed proof is authoritative.</sub>\n"
        )
        return body

    def publish_fix(
        self,
        repo_path: str,
        branch: str,
        patch_files: dict[str, str],
        commit_message: str,
        title: str,
        body: str,
        draft: bool = False,
        extra_files: dict[str, str] | None = None,
    ) -> str | None:
        """Create branch, apply patches + proof artifacts, commit, push, then open PR."""
        all_files = dict(patch_files)
        if extra_files:
            all_files.update(extra_files)

        if all_files and not self.create_branch_and_commit(
            repo_path, branch, all_files, commit_message, amend_with_proof=True
        ):
            return None
        return self.create_pr(title=title, body=body, branch=branch, draft=draft)

    def publish_fix_with_proof(
        self,
        repo_path: str,
        branch: str,
        patch_files: dict[str, str],
        bundle: VerificationBundle,
        commit_message: str,
        title: str,
        body: str = "",
        draft: bool = False,
        why_section: str = "",
        what_section: str = "",
        review_section: str = "",
        expected_source_hashes: dict | None = None,
    ) -> tuple[PublicationResult, VerificationBundle]:
        """Publish a tested-code commit followed by a separate proof-only commit."""
        if self.settings.github_dry_run:
            return PublicationResult(status="dry_run", reason="GitHub publication is disabled by GITHUB_DRY_RUN=true. Enable live publication and start a new run to create a PR."), bundle
        if not self.settings.github_token:
            return PublicationResult(status="disabled", reason="GitHub publication is not configured"), bundle
        if not patch_files:
            return PublicationResult(status="disabled", reason="No repair files to publish"), bundle

        stage = "prepare"
        tested_sha: str | None = None
        published_sha: str | None = None
        artifact_hash: str | None = None
        final_bundle = bundle.model_copy(deep=True)
        try:
            from git import Repo

            repo = Repo(repo_path)
            stage = "resolve_destination"
            repository = self._publication_target(repo)
            self._checkout_branch(repo, branch)
            root = Path(repo_path)
            stage = "commit_tested_code"
            repo.git.reset()
            dirty = set(repo.git.diff("--name-only").splitlines())
            untracked_relevant = {
                path for path in repo.untracked_files
                if not path.startswith((".pytest_cache/", ".mypy_cache/", ".ruff_cache/"))
                and "/__pycache__/" not in f"/{path}"
            }
            if (dirty | untracked_relevant) - patch_files.keys():
                raise ValueError("Validated checkout has unrecorded source changes")
            for path, content in patch_files.items():
                p = (root / path).resolve()
                if not p.is_relative_to(root.resolve()) or not p.is_file():
                    raise ValueError("Patch path is absent or outside the repository")
                if p.read_text(encoding="utf-8") != content:
                    raise ValueError("Validated checkout differs from patch payload")
                recorded = (expected_source_hashes or {}).get(path, {}).get("patched")
                if recorded and hashlib.sha256(content.encode()).hexdigest() != recorded:
                    raise ValueError("Patch payload differs from A8 validated source hash")
                p.parent.mkdir(parents=True, exist_ok=True)
                repo.index.add([path])
            if not repo.index.diff("HEAD"):
                raise ValueError("No tested code change is available to commit")
            repo.index.commit(commit_message)
            tested_sha = repo.head.commit.hexsha
            base_sha = final_bundle.steps[0].base_commit if final_bundle.steps else ""
            if not base_sha:
                raise ValueError("Proof has no base commit")
            repo.git.cat_file("-e", f"{base_sha}^{{commit}}")
            repo.git.merge_base("--is-ancestor", base_sha, tested_sha)
            for path, content in patch_files.items():
                if (repo.head.commit.tree / path).data_stream.read() != content.encode("utf-8"):
                    raise ValueError("Tested commit does not contain the validated patch payload")

            for step in final_bundle.steps:
                step.patch_commit = tested_sha
            final_bundle.bundle_hash = compute_bundle_hash(final_bundle.steps)
            artifact_hash = proof_artifact_hash(final_bundle)

            stage = "commit_proof"
            workflow_yaml = generate_verification_workflow(final_bundle)
            proof_path = proof_bundle_relative_path(final_bundle)
            workflow_path = workflow_relative_path(final_bundle)

            proof_abs = root / proof_path
            proof_abs.parent.mkdir(parents=True, exist_ok=True)
            proof_abs.write_text(serialize_verification_bundle(final_bundle), encoding="utf-8")

            workflow_abs = root / workflow_path
            workflow_abs.parent.mkdir(parents=True, exist_ok=True)
            workflow_abs.write_text(workflow_yaml, encoding="utf-8")

            repo.index.add([proof_path, workflow_path])
            repo.index.commit("proof: pin tested patch and verification workflow")
            candidate_head_sha = repo.head.commit.hexsha
            if repo.head.commit.parents[0].hexsha != tested_sha:
                raise ValueError("Proof commit replaced the tested code commit")
            if proof_artifact_hash(final_bundle) != artifact_hash:
                raise ValueError("Proof snapshot changed during publication")

            stage = "push"
            origin = repo.remote(name="origin")
            with self._git_auth(repo):
                origin.push(refspec=f"{branch}:{branch}").raise_if_error()
                self._verify_remote_branch(repo, branch, tested_sha, candidate_head_sha)
            published_sha = candidate_head_sha

            stage = "create_pr"
            final_body = self.format_pr_body_with_proof(
                final_bundle, why_section, what_section, review_section,
                published_head_sha=published_sha, artifact_hash=artifact_hash,
            )
            if tested_sha not in final_body or artifact_hash not in final_body or published_sha not in final_body:
                raise ValueError("PR body disagrees with proof snapshot")
            url = self.create_pr(title=title, body=final_body, branch=branch, draft=draft,
                                 repository=repository)
            if not url:
                raise ValueError("PR operation returned no URL")
            with self._git_auth(repo):
                self._verify_remote_branch(repo, branch, tested_sha, published_sha)
            return PublicationResult(
                status="published", tested_patch_sha=tested_sha,
                published_head_sha=published_sha, proof_artifact_hash=artifact_hash,
                pr_url=url,
            ), final_bundle
        except Exception as exc:
            return PublicationResult(
                status="failed", tested_patch_sha=tested_sha,
                published_head_sha=published_sha, proof_artifact_hash=artifact_hash,
                reason=f"GitHub {stage} failed ({type(exc).__name__}). " + {
                    "resolve_destination": "The submitted repository must have an origin pointing to its GitHub destination.",
                    "push": self._push_failure_hint(exc),
                    "create_pr": "Check pull-request write access and the repository default branch.",
                }.get(stage, "The validated repair and publication checkout could not be reconciled."),
            ), final_bundle

    @staticmethod
    def _push_failure_hint(exc: Exception) -> str:
        """Classify Git diagnostics without returning commands or credential-bearing output."""
        diagnostic = " ".join(str(value) for value in (
            getattr(exc, "stderr", ""), getattr(exc, "stdout", ""), str(exc),
        )).lower()
        if "workflow" in diagnostic and any(word in diagnostic for word in (
            "refusing", "permission", "scope", "not allowed",
        )):
            return "GitHub rejected a workflow update. The publishing token needs permission to write workflows."
        if any(word in diagnostic for word in ("authentication failed", "invalid username or token", "could not read username", "bad credentials")):
            return "Git authentication failed. Check that the running backend loaded a valid, unexpired GitHub token."
        if any(word in diagnostic for word in ("gh013", "gh006", "repository rule", "protected branch", "push protection")):
            return "GitHub rejected the push under repository rules or push protection. Inspect the repository rules and rejected changes."
        if any(word in diagnostic for word in ("permission to", "write access", "repository not found", "error: 403")):
            return "GitHub denied repository access. Check the token's repository selection, Contents write permission, and account access."
        if any(word in diagnostic for word in ("could not resolve host", "failed to connect", "connection timed out", "network is unreachable")):
            return "The backend could not reach GitHub. Check its network connection and DNS."
        if any(word in diagnostic for word in ("non-fast-forward", "fetch first")):
            return "The remote branch has conflicting history. Retry publication on a fresh repair branch."
        return "The push failed, but its cause could not be classified. Inspect backend Git diagnostics; permissions are not confirmed as the cause."

    @contextmanager
    def _git_auth(self, repo):
        """Use the configured token for HTTPS Git, without storing it in origin."""
        env = {"GIT_TERMINAL_PROMPT": "0"}
        if repo.remote(name="origin").url.startswith("https://github.com/"):
            encoded = base64.b64encode(f"x-access-token:{self.settings.github_token}".encode()).decode()
            env.update({
                "GIT_CONFIG_COUNT": "1",
                "GIT_CONFIG_KEY_0": "http.https://github.com/.extraheader",
                "GIT_CONFIG_VALUE_0": f"AUTHORIZATION: basic {encoded}",
            })
        with repo.git.custom_environment(**env):
            yield

    @staticmethod
    def _publication_target(repo) -> str:
        """The submitted checkout's origin is the publication destination."""
        origin = repo.remote(name="origin")
        fetch = GitHubPRService._github_repository(origin.url)
        push_urls = list(origin.urls)
        explicit_push = repo.git.config("--get-all", "remote.origin.pushurl", with_exceptions=False)
        if explicit_push:
            push_urls = explicit_push.splitlines()
        if not fetch or not push_urls or any(
            GitHubPRService._github_repository(url) != fetch for url in push_urls
        ):
            raise ValueError("Origin must fetch and push the same GitHub repository")
        return fetch

    @staticmethod
    def _github_repository(url: str) -> str | None:
        if url.startswith("git@github.com:"):
            path = url[len("git@github.com:"):]
        else:
            parsed = urlparse(url)
            if parsed.hostname != "github.com" or parsed.scheme not in {"https", "ssh"}:
                return None
            path = parsed.path.lstrip("/")
        path = path.rstrip("/").removesuffix(".git")
        return path if re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", path) else None

    @staticmethod
    def _verify_remote_branch(repo, branch: str, tested_sha: str, published_sha: str) -> None:
        remote = repo.git.ls_remote("origin", f"refs/heads/{branch}")
        remote_sha = remote.split()[0] if remote else None
        if remote_sha != published_sha or repo.head.commit.hexsha != published_sha:
            raise ValueError("Remote branch head differs from published proof head")
        repo.git.merge_base("--is-ancestor", tested_sha, published_sha)

    def create_pr(
        self,
        title: str,
        body: str,
        branch: str,
        draft: bool = False,
        repository: str | None = None,
    ) -> str | None:
        owner = self.settings.github_repo_owner
        name = self.settings.github_repo_name
        if repository:
            owner, name = repository.split("/", 1)

        if self.settings.github_dry_run or not self.settings.github_token:
            # A dry-run URL that names an unconfigured target is a guess about
            # where this PR would have gone. Say there is no target instead.
            if not owner or not name:
                return None
            return f"https://github.com/{owner}/{name}/pull/DRY_RUN"

        if not owner or not name:
            # Refusing beats opening a pull request against whatever repository
            # the defaults happen to name.
            return None

        from github import Github

        g = Github(self.settings.github_token)
        repo = g.get_repo(f"{owner}/{name}")
        base = repo.default_branch
        existing = list(repo.get_pulls(state="open", head=f"{owner}:{branch}", base=base))
        if existing:
            pr = existing[0]
            pr.edit(body=body)
            return pr.html_url
        pr = repo.create_pull(
            title=title,
            body=body,
            head=branch,
            base=base,
            draft=draft,
        )
        return pr.html_url

    def create_branch_and_commit(
        self,
        repo_path: str,
        branch: str,
        files: dict[str, str],
        message: str,
        amend_with_proof: bool = False,
    ) -> bool:
        if self.settings.github_dry_run:
            return True
        if not self.settings.github_token:
            return False
        if not files:
            return True
        try:
            from git import Repo

            repo = Repo(repo_path)
            self._checkout_branch(repo, branch)

            root = Path(repo_path)
            for path, content in files.items():
                p = root / path
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(content, encoding="utf-8")
                repo.index.add([path])
            if repo.is_dirty(untracked_files=True):
                repo.index.commit(message)
                if not amend_with_proof:
                    origin = repo.remote(name="origin")
                    origin.push(refspec=f"{branch}:{branch}")
            return True
        except Exception:
            return False

    def _checkout_branch(self, repo, branch: str) -> None:
        if repo.head.is_detached:
            repo.git.checkout("-B", branch)
            return
        existing = [h.name for h in repo.heads]
        if branch in existing:
            repo.git.checkout(branch)
        else:
            repo.git.checkout("-b", branch)


def _bundle_json(bundle: VerificationBundle) -> str:
    return serialize_verification_bundle(bundle)
